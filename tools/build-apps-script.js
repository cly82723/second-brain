// Joins the web app's parts into ONE file to paste into Apps Script: apps-script/dist/Code.gs.
// core/logic.js is shared with the page, so the calendar rules exist in one place only.
// Usage: node tools/build-apps-script.js   (tests/build.test.js checks dist/ is up to date)
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const PARTS = ["core/logic.js", "apps-script/Schools.gs", "apps-script/Validate.gs", "apps-script/Store.gs",
  "apps-script/Code.gs", "apps-script/Import.gs", "apps-script/Email.gs"];
const DIST = path.join(ROOT, "apps-script/dist");

function buildCode() {
  const header = "/* Teachers' Second Brain: the whole web app in one file.\n" +
    "   GENERATED by tools/build-apps-script.js from the files listed below; edit those, not this.\n" +
    "   Paste ALL of this into Code.gs in Apps Script, then Deploy → Manage deployments → New version.\n" +
    PARTS.map((p) => "     - " + p).join("\n") + " */\n";
  return header + PARTS.map((p) => "\n// ===== " + p + " =====\n" + fs.readFileSync(path.join(ROOT, p), "utf8").replace(/\r\n/g, "\n")).join("");
}

function build() {
  fs.mkdirSync(DIST, { recursive: true });
  fs.writeFileSync(path.join(DIST, "Code.gs"), buildCode());
  fs.copyFileSync(path.join(ROOT, "apps-script/appsscript.json"), path.join(DIST, "appsscript.json"));
}

if (require.main === module) { build(); console.log("Wrote apps-script/dist/Code.gs and appsscript.json"); }
module.exports = { buildCode, PARTS };
